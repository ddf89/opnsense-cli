// NAT rules of Firewall > NAT: Source NAT (api/firewall/source_nat), Destination NAT / port forward
// (api/firewall/d_nat), One-to-One (api/firewall/one_to_one) and NPTv6 (api/firewall/npt). All four controllers
// share the same methods (search_rule, get_rule, add_rule, set_rule, del_rule, toggle_rule, move_rule_before,
// download_rules, apply), so one implementation (NatRules) serves them, see FirewallApi.SourceNat etc.
//
// OPNsense 26.7 behaviour (verified live):
//   - set_rule on an unknown but well-formed uuid creates the rule from the model defaults (enabled!), malformed
//     uuids answer a bare "failed"; Update checks the existence first
//   - get_rule/<unknown uuid> answers [], del_rule "not found", toggle_rule "failed", move_rule_before and
//     toggle_rule_log HTTP 500 {"errorMessage":"..."}
//   - search_rule always includes the rules OPNsense generates (is_automatic, uuids like automatic_wan or
//     lockout_0), even when a searchPhrase excludes them; they can not be changed
//   - source_nat/search_rule only returns the manual rules in the hybrid and manual (advanced) outbound NAT modes;
//     in the automatic and disabled modes they are only listed by download_rules (CSV), List merges them in
//   - d_nat is shaped like the legacy port forwards: "descr" instead of "description", a "disabled" flag instead
//     of "enabled", toggle_rule/<uuid>/<disabled> and no "changed" in its answer, nested source / destination
//     (flattened to "source.network" etc. by search_rule)
//   - there is no savepoint / rollback for NAT: apply (on any of the four controllers) runs "filter reload
//     skip_alias", which reloads the whole firewall (rules and NAT)

// NatRuleFields are the fields of a rule by their flat API names, nested d_nat fields with a dot
// ("destination.port"). Values are sent as given, "" clears a field
type NatRuleFields map[string]string

// NatRule is one rule as listed by search_rule (or download_rules for inactive source NAT rules)
type NatRule struct {
	Uuid string
	// Fields holds every string field of the row by its flat API name, including the descriptions of option
	// values ("%interface"); booleans are "1" / "0"
	Fields NatRuleFields
	// Automatic rules are generated by OPNsense (e.g. the anti-lockout or the automatic outbound NAT rules), they
	// can not be changed or removed
	Automatic bool
	// Inactive source NAT rules are ignored by the current outbound NAT mode (automatic or disabled)
	Inactive bool
	// Raw is the row as the API returned it (a JSON object)
	Raw json.RawMessage
}

// natKind describes the differences between the four NAT controllers
type natKind struct {
	controller  string // source_nat
	name        string // source NAT rule
	description string // the description field: description or descr
	// disabledFlag is true when the on/off field is "disabled" (d_nat) instead of "enabled"
	disabledFlag bool
	// listAll lists the configured rules with download_rules too (source NAT hides them in some modes)
	listAll bool
}

var (
	natSource      = natKind{controller: "source_nat", name: "source NAT rule", description: "description", listAll: true}
	natDestination = natKind{controller: "d_nat", name: "destination NAT rule", description: "descr", disabledFlag: true}
	natOneToOne    = natKind{controller: "one_to_one", name: "one-to-one NAT rule", description: "description"}
	natNpt         = natKind{controller: "npt", name: "NPTv6 rule", description: "description"}
)

// NatRules manages the rules of one NAT type
type NatRules struct {
	opn  *FirewallApi
	kind natKind
}

// SourceNat returns the Source NAT (outbound NAT) rules
func (opn *FirewallApi) SourceNat() *NatRules { return &NatRules{opn: opn, kind: natSource} }

// DestinationNat returns the Destination NAT (port forward) rules
func (opn *FirewallApi) DestinationNat() *NatRules { return &NatRules{opn: opn, kind: natDestination} }

// OneToOne returns the One-to-One NAT rules
func (opn *FirewallApi) OneToOne() *NatRules { return &NatRules{opn: opn, kind: natOneToOne} }

// Npt returns the NPTv6 rules
func (opn *FirewallApi) Npt() *NatRules { return &NatRules{opn: opn, kind: natNpt} }

// Name is what a rule of this type is called in messages, e.g. "source NAT rule"
func (rules *NatRules) Name() string { return rules.kind.name }

// DescriptionField is the API field holding the description: "description", or "descr" for d_nat
func (rules *NatRules) DescriptionField() string { return rules.kind.description }

// DisabledField is the API field of the on/off state: "enabled", or "disabled" for d_nat
func (rules *NatRules) DisabledField() string {
	if rules.kind.disabledFlag {
		return "disabled"
	}
	return "enabled"
}

// DisabledValue returns the value of DisabledField for a disabled (or enabled) rule
func (rules *NatRules) DisabledValue(disabled bool) string {
	if disabled == rules.kind.disabledFlag {
		return "1"
	}
	return "0"
}

// Description returns the description of rule
func (rules *NatRules) Description(rule NatRule) string { return rule.Fields[rules.kind.description] }

// Disabled reports whether rule is disabled
func (rules *NatRules) Disabled(rule NatRule) bool {
	var value = rule.Fields[rules.DisabledField()]
	if rules.kind.disabledFlag {
		return value == "1"
	}
	return value == "0"
}

func (rules *NatRules) endpoint(method string, path ...string) string {
	var endpoint = rules.opn.endpoint("firewall", rules.kind.controller, method)
	if len(path) > 0 {
		endpoint += "/" + strings.Join(path, "/")
	}
	return endpoint
}

func (rules *NatRules) notFound(uuid string, err error) error {
	return &coreapi.NotFoundError{Name: fmt.Sprintf("%s %s", rules.kind.name, uuid), Err: err}
}

// natFlatten converts a search_rule row into flat string fields: strings as they are, booleans as "1" / "0",
// numbers as text; lists and objects (alias_meta_*, category_colors) are left out
func natFlatten(row map[string]json.RawMessage) NatRuleFields {
	var fields = NatRuleFields{}
	for name, raw := range row {
		var text string
		if err := json.Unmarshal(raw, &text); err == nil {
			fields[name] = text
			continue
		}
		var flag bool
		if err := json.Unmarshal(raw, &flag); err == nil {
			fields[name] = map[bool]string{true: "1", false: "0"}[flag]
			continue
		}
		var number json.Number
		if err := json.Unmarshal(raw, &number); err == nil {
			fields[name] = number.String()
		}
	}
	return fields
}

// List returns all rules in the order of search_rule (the order OPNsense evaluates them in), followed by the
// inactive source NAT rules
func (rules *NatRules) List() ([]NatRule, error) {
	var rows, err = coreapi.Search[json.RawMessage](rules.opn.OPNsense, rules.endpoint("search_rule"), "")
	if err != nil {
		return nil, err
	}

	var result = make([]NatRule, 0, len(rows))
	var listed = map[string]bool{}
	for _, raw := range rows {
		var row map[string]json.RawMessage
		if err := json.Unmarshal(raw, &row); err != nil {
			return nil, fmt.Errorf("unexpected %s from OPNsense: %w", rules.kind.name, err)
		}
		var fields = natFlatten(row)
		var rule = NatRule{Uuid: fields["uuid"], Fields: fields, Automatic: fields["is_automatic"] == "1", Raw: raw}
		listed[rule.Uuid] = true
		result = append(result, rule)
	}

	if rules.kind.listAll {
		var configured, csvErr = rules.download()
		if csvErr != nil {
			return nil, csvErr
		}
		for _, rule := range configured {
			if !listed[rule.Uuid] {
				rule.Inactive = true
				result = append(result, rule)
			}
		}
	}
	return result, nil
}

// download returns the configured rules from download_rules (CSV with ; separators and an @uuid column), sorted
// by sequence
func (rules *NatRules) download() ([]NatRule, error) {
	var endpoint = rules.endpoint("download_rules")
	var request, err = http.NewRequest("GET", endpoint, nil)
	if err != nil {
		return nil, err
	}
	response, err := rules.opn.Send(request)
	if err != nil {
		return nil, err
	}
	defer func() { _ = response.Body.Close() }()
	body, err := io.ReadAll(response.Body)
	if err != nil {
		return nil, err
	}
	if response.StatusCode != http.StatusOK {
		return nil, &coreapi.HttpError{StatusCode: response.StatusCode, Message: strings.TrimSpace(string(body))}
	}
	if len(bytes.TrimSpace(body)) == 0 { // no rules
		return nil, nil
	}

	var reader = csv.NewReader(bytes.NewReader(body))
	reader.Comma = ';'
	reader.LazyQuotes = true
	records, err := reader.ReadAll()
	if err != nil {
		return nil, fmt.Errorf("could not read the rules from %s: %w", endpoint, err)
	}
	var header = records[0]
	var result = make([]NatRule, 0, len(records)-1)
	for _, record := range records[1:] {
		var fields = NatRuleFields{}
		for i, name := range header {
			if i < len(record) {
				fields[name] = record[i]
			}
		}
		fields["uuid"] = fields["@uuid"]
		delete(fields, "@uuid")
		var raw, _ = json.Marshal(fields)
		result = append(result, NatRule{Uuid: fields["uuid"], Fields: fields, Raw: raw})
	}
	sort.SliceStable(result, func(i, j int) bool {
		var a, _ = strconv.Atoi(result[i].Fields["sequence"])
		var b, _ = strconv.Atoi(result[j].Fields["sequence"])
		return a < b
	})
	return result, nil
}

// natFind returns the rule with uuid (case-insensitive) from list
func (rules *NatRules) natFind(list []NatRule, uuid string) (NatRule, error) {
	for _, rule := range list {
		if strings.EqualFold(rule.Uuid, uuid) {
			return rule, nil
		}
	}
	return NatRule{}, rules.notFound(uuid, nil)
}

// Get returns the rule with the given uuid, *coreapi.NotFoundError if there is none
func (rules *NatRules) Get(uuid string) (NatRule, error) {
	var list, err = rules.List()
	if err != nil {
		return NatRule{}, err
	}
	return rules.natFind(list, uuid)
}

// changeable returns the configured (not automatic) rule with uuid
func (rules *NatRules) changeable(uuid string) (NatRule, error) {
	if uuid == "" {
		return NatRule{}, fmt.Errorf("no %s uuid given", rules.kind.name)
	}
	var rule, err = rules.Get(uuid)
	if err != nil {
		return NatRule{}, err
	}
	if rule.Automatic {
		return NatRule{}, fmt.Errorf("the %s %s is generated by OPNsense and can not be changed", rules.kind.name, rule.Uuid)
	}
	return rule, nil
}

// natBody nests the flat fields ("destination.port") into {"rule":{...}}
func natBody(fields NatRuleFields) map[string]any {
	var rule = map[string]any{}
	for name, value := range fields {
		var parent, child, nested = strings.Cut(name, ".")
		if !nested {
			rule[name] = value
			continue
		}
		var container, ok = rule[parent].(map[string]any)
		if !ok {
			container = map[string]any{}
			rule[parent] = container
		}
		container[child] = value
	}
	return map[string]any{"rule": rule}
}

// Create adds a rule from fields (the model defaults apply to the fields not given) and returns its uuid.
// OPNsense enables new rules unless the fields disable them
func (rules *NatRules) Create(fields NatRuleFields) (string, error) {
	return rules.opn.Mutate(rules.endpoint("add_rule"), natBody(fields))
}

// Update changes the given fields of the rule with uuid, the others are kept. Returns *coreapi.NotFoundError when
// the rule does not exist (OPNsense would create it) and an error for automatic rules
func (rules *NatRules) Update(uuid string, fields NatRuleFields) error {
	var rule, err = rules.changeable(uuid)
	if err != nil {
		return err
	}
	if _, err := rules.opn.Mutate(rules.endpoint("set_rule", rule.Uuid), natBody(fields)); err != nil {
		var validationErr *coreapi.ValidationError
		if errors.As(err, &validationErr) && len(validationErr.Validations) == 0 {
			return rules.notFound(uuid, err)
		}
		return err
	}
	return nil
}

// Remove deletes the rule with uuid, *coreapi.NotFoundError if it does not exist
func (rules *NatRules) Remove(uuid string) error {
	if uuid == "" {
		return fmt.Errorf("no %s uuid given", rules.kind.name)
	}
	if _, err := rules.opn.Mutate(rules.endpoint("del_rule", uuid), nil); err != nil {
		if coreapi.IsNotFound(err) {
			return rules.notFound(uuid, err)
		}
		return err
	}
	return nil
}

// SetEnabled enables or disables the rule with uuid and returns whether its state changed
func (rules *NatRules) SetEnabled(uuid string, enabled bool) (bool, error) {
	var rule, err = rules.changeable(uuid)
	if err != nil {
		return false, err
	}
	var endpoint = rules.endpoint("toggle_rule", rule.Uuid, rules.DisabledValue(!enabled))
	var result struct {
		Result string `json:"result"`
	}
	if err := rules.opn.DoJSON("POST", endpoint, nil, &result); err != nil {
		return false, err
	}
	switch result.Result {
	case "Enabled", "Disabled":
		return rules.Disabled(rule) == enabled, nil
	case "failed": // removed meanwhile
		return false, rules.notFound(uuid, nil)
	default:
		return false, fmt.Errorf("unexpected result from %s: %q", endpoint, result.Result)
	}
}

// MoveBefore moves the rule with uuid right before the rule with before (both must be configured rules)
func (rules *NatRules) MoveBefore(uuid string, before string) error {
	var list, err = rules.List()
	if err != nil {
		return err
	}
	var moving, target NatRule
	for _, pair := range []struct {
		uuid string
		rule *NatRule
	}{{uuid, &moving}, {before, &target}} {
		var found, findErr = rules.natFind(list, pair.uuid)
		if findErr != nil {
			return findErr
		}
		if found.Automatic {
			return fmt.Errorf("the %s %s is generated by OPNsense, rules can not be moved around it", rules.kind.name, found.Uuid)
		}
		*pair.rule = found
	}
	if moving.Uuid == target.Uuid {
		return fmt.Errorf("can not move the %s %s before itself", rules.kind.name, moving.Uuid)
	}

	var result struct {
		Status  string `json:"status"`
		Message string `json:"message"`
	}
	var endpoint = rules.endpoint("move_rule_before", moving.Uuid, target.Uuid)
	if err := rules.opn.DoJSON("POST", endpoint, nil, &result); err != nil {
		return err
	}
	if result.Status != "ok" {
		return fmt.Errorf("moving the %s failed: %s %s", rules.kind.name, result.Status, result.Message)
	}
	return nil
}

// MoveToEnd gives the rule with uuid a sequence after all other configured rules (unchanged when it is last already)
func (rules *NatRules) MoveToEnd(uuid string) error {
	var list, err = rules.List()
	if err != nil {
		return err
	}
	var rule, findErr = rules.natFind(list, uuid)
	if findErr != nil {
		return findErr
	}
	if rule.Automatic {
		return fmt.Errorf("the %s %s is generated by OPNsense and can not be moved", rules.kind.name, rule.Uuid)
	}
	var own, _ = strconv.Atoi(rule.Fields["sequence"])
	var last int
	var shared bool
	for _, other := range list {
		if other.Automatic || other.Uuid == rule.Uuid {
			continue
		}
		var sequence, _ = strconv.Atoi(other.Fields["sequence"])
		last = max(last, sequence)
		shared = shared || sequence == own
	}
	if own > last && !shared {
		return nil
	}
	const maxSequence = 999999
	if last >= maxSequence {
		return fmt.Errorf("can not move the %s to the end, the last rule has the highest sequence %d already", rules.kind.name, maxSequence)
	}
	return rules.Update(rule.Uuid, NatRuleFields{"sequence": strconv.Itoa(min(last+100, maxSequence))})
}

// Options returns the option keys of the option fields of a new rule (e.g. "interface", "protocol"), from get_rule
func (rules *NatRules) Options() (map[string][]string, error) {
	var container struct {
		Rule map[string]json.RawMessage `json:"rule"`
	}
	if err := rules.opn.DoJSON("GET", rules.endpoint("get_rule"), nil, &container); err != nil {
		return nil, err
	}
	var options = map[string][]string{}
	for field, raw := range container.Rule {
		var values map[string]struct {
			Value    string `json:"value"`
			Selected any    `json:"selected"`
		}
		if err := json.Unmarshal(raw, &values); err != nil {
			continue
		}
		var keys = make([]string, 0, len(values))
		var isOptionList = true
		for key, option := range values {
			if option.Selected == nil { // a nested container like d_nat source, no option list
				isOptionList = false
				break
			}
			keys = append(keys, key)
		}
		if isOptionList {
			sort.Strings(keys)
			options[field] = keys
		}
	}
	return options, nil
}

// Apply reloads the firewall rules and NAT ("filter reload skip_alias"), activating all saved firewall changes.
// There is no rollback
func (rules *NatRules) Apply() error {
	var result struct {
		Status string `json:"status"`
	}
	if err := rules.opn.DoJSON("POST", rules.endpoint("apply"), nil, &result); err != nil {
		return err
	}
	if !strings.EqualFold(strings.TrimSpace(result.Status), "ok") {
		return fmt.Errorf("applying the firewall changes failed: %q", strings.TrimSpace(result.Status))
	}
	return nil
}

// Outbound (source) NAT modes, see SourceNatMode
const (
	SourceNatModeAutomatic = "automatic"
	SourceNatModeHybrid    = "hybrid"
	SourceNatModeManual    = "advanced"
	SourceNatModeDisabled  = "disabled"
)

// SourceNatModes are the outbound NAT modes in the order OPNsense offers them
var SourceNatModes = []string{SourceNatModeAutomatic, SourceNatModeHybrid, SourceNatModeManual, SourceNatModeDisabled}

// SourceNatMode returns the outbound NAT mode: automatic (only the automatic rules), hybrid (manual and
// automatic rules), advanced (manual rules only) or disabled (no source NAT)
func (opn *FirewallApi) SourceNatMode() (string, error) {
	var container struct {
		Filter struct {
			General struct {
				Mode map[string]struct {
					Selected any `json:"selected"`
				} `json:"snat_mode"`
			} `json:"general"`
		} `json:"filter"`
	}
	if err := opn.DoJSON("GET", opn.endpoint("firewall", "source_nat", "get"), nil, &container); err != nil {
		return "", err
	}
	for mode, option := range container.Filter.General.Mode {
		if option.Selected == true || fmt.Sprint(option.Selected) == "1" {
			return mode, nil
		}
	}
	return "", errors.New("OPNsense reported no outbound NAT mode")
}

// SourceNatSetMode saves the outbound NAT mode (one of SourceNatModes), it is activated by Apply
func (opn *FirewallApi) SourceNatSetMode(mode string) error {
	var known bool
	for _, available := range SourceNatModes {
		known = known || available == mode
	}
	if !known {
		return fmt.Errorf("unknown outbound NAT mode %q, the modes are %s", mode, strings.Join(SourceNatModes, ", "))
	}
	var body = map[string]any{"filter": map[string]any{"general": map[string]string{"snat_mode": mode}}}
	_, err := opn.Mutate(opn.endpoint("firewall", "source_nat", "set"), body)
	return err
}
