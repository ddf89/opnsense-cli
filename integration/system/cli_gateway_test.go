//go:build integration

package integrationsystem

import (
	"encoding/json"
	"strings"
	"testing"

	api "opnsense-cli/opnsense/api"
)

// TestCliGatewayLifecycle drives /system/gateway with a LAN gateway (192.168.1.242/243, never upstream, monitoring
// disabled, never applied). apply and the override of the generated WAN gateways are only tested with fakes
func TestCliGatewayLifecycle(t *testing.T) {
	var sys = systemApi(t)
	const menu = "/system/gateway"
	var name = gatewayTestName(t)
	var description = testDescription("gateway-cli")

	var added = mustOpn(t, menu, "add", "name="+name, "interface=LAN", "address=192.168.1.242", "description="+description,
		"priority=200", "upstream=no", "monitor-disabled=yes")
	var uuid = uuidFrom(t, added)
	if strings.TrimSpace(added.stdout) != uuid {
		t.Errorf("add must print only the uuid:\n%s", added)
	}
	cleanupGateway(t, sys, uuid)

	t.Run("print and show", func(t *testing.T) {
		var printed = mustOpn(t, menu, "print", "search="+name)
		requireContains(t, printed, printed.stdout, name, "lan", "ipv4", "192.168.1.242", "200")
		if lines := strings.Split(strings.TrimSpace(printed.stdout), "\n"); len(lines) != 2 {
			t.Errorf("want the header and one row:\n%s", printed)
		}

		var shown = mustOpn(t, menu, "show", strings.ToUpper(name))
		requireContains(t, shown, shown.stdout, "uuid:                  "+uuid, "description:           "+description,
			"configured:            yes", "upstream:              no", "monitor-disabled:      yes", "latency-high:          500 (default)")

		var asJSON = mustOpn(t, menu, "print", "json", "search="+name)
		var row map[string]any
		if err := json.Unmarshal([]byte(strings.TrimSpace(asJSON.stdout)), &row); err != nil || row["uuid"] != uuid {
			t.Errorf("want the raw row as JSON, got %v:\n%s", err, asJSON)
		}
	})

	t.Run("set changes only the given fields", func(t *testing.T) {
		requireNoStdout(t, mustOpn(t, menu, "set", uuid, "priority=7", "weight=3", "loss-high=50"))
		var gateway, err = sys.GatewayGet(uuid)
		if err != nil {
			t.Fatal(err)
		}
		if gateway.Priority != "7" || gateway.Weight != "3" || gateway.LossHigh != "50" || gateway.Address != "192.168.1.242" ||
			gateway.Description != description {
			t.Errorf("unexpected gateway after set %+v", gateway)
		}
		var refused = mustFailOpn(t, menu, "set", uuid, "name=other")
		requireContains(t, refused, refused.stderr, "can not be changed")
		refused = mustFailOpn(t, menu, "set", uuid, "loss-low=60") // above loss-high 50
		requireContains(t, refused, refused.stderr, "Packet Loss")
	})

	t.Run("disable and enable", func(t *testing.T) {
		requireNoStdout(t, mustOpn(t, menu, "disable", name))
		var shown = mustOpn(t, menu, "show", uuid)
		requireContains(t, shown, shown.stdout, "disabled:              yes")
		var again = mustOpn(t, menu, "disable", name)
		requireContains(t, again, again.stderr, "already disabled")
		requireNoStdout(t, mustOpn(t, menu, "enable", name))
		shown = mustOpn(t, menu, "show", uuid)
		requireContains(t, shown, shown.stdout, "disabled:              no")
	})

	t.Run("add of an existing name needs replace", func(t *testing.T) {
		var refused = mustFailOpn(t, menu, "add", "name="+name, "interface=lan", "address=192.168.1.243", "description="+description)
		requireContains(t, refused, refused.stderr, "exists already", uuid)

		var replaced = mustOpn(t, menu, "add", "name="+name, "interface=lan", "address=192.168.1.243", "description="+description, "replace")
		if strings.TrimSpace(replaced.stdout) != uuid {
			t.Errorf("replace must print the uuid of the replaced gateway:\n%s", replaced)
		}
		var gateway, err = sys.GatewayGet(uuid)
		if err != nil {
			t.Fatal(err)
		}
		// replaced completely: the fields set before are back at their defaults
		if gateway.Address != "192.168.1.243" || gateway.Priority != "255" || gateway.Weight != "1" || gateway.LossHigh != "" {
			t.Errorf("unexpected gateway after replace %+v", gateway)
		}
	})

	t.Run("monitor once", func(t *testing.T) {
		var monitored = mustOpn(t, menu, "monitor", "once")
		requireContains(t, monitored, monitored.stdout, "NAME", "LOSS", "DELAY", name)
	})

	t.Run("generated gateways can not be removed", func(t *testing.T) {
		var gateways, err = sys.GatewayList()
		if err != nil {
			t.Fatal(err)
		}
		for _, gateway := range gateways {
			if !gateway.IsConfigured() {
				var refused = mustFailOpn(t, menu, "remove", gateway.Name)
				requireContains(t, refused, refused.stderr, "generated by OPNsense")
				break
			}
		}
	})

	t.Run("remove", func(t *testing.T) {
		requireNoStdout(t, mustOpn(t, menu, "remove", uuid))
		if _, err := sys.GatewayGet(uuid); !api.IsNotFound(err) {
			t.Errorf("want the gateway to be gone, got %v", err)
		}
		var refused = mustFailOpn(t, menu, "show", uuid)
		requireContains(t, refused, refused.stderr, "not found")
	})
}
