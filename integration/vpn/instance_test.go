// instanceTestTrust is a test CA and a server certificate signed by it (trust store refids and descriptions)
type instanceTestTrust struct {
	CaRef, CaDescr, CertRef, CertDescr string
}

// instanceTestCertificates creates an internal CA and a server certificate in the trust store, removed (cert
// first) when the test ends
func instanceTestCertificates(t *testing.T, label string) instanceTestTrust {
	t.Helper()
	var core = coreApi(t)
	var trust = instanceTestTrust{CaDescr: testDescription(label + " ca"), CertDescr: testDescription(label + " cert")}
	var remove = func(kind string, uuid string) {
		t.Cleanup(func() {
			if _, err := core.Mutate(core.EndpointForModule("trust/"+kind+"/del/"+uuid), nil); err != nil {
				t.Errorf("cleanup: removing %s %s: %v", kind, uuid, err)
			}
		})
	}
	var refid = func(kind string, uuid string) string {
		var rows, err = api.Search[struct {
			Uuid  string `json:"uuid"`
			Refid string `json:"refid"`
		}](core, core.EndpointForModule("trust/"+kind+"/search"), runPrefix)
		if err != nil {
			t.Fatalf("trust/%s/search: %v", kind, err)
		}
		for _, row := range rows {
			if row.Uuid == uuid {
				return row.Refid
			}
		}
		t.Fatalf("the new %s %s is not in the trust store", kind, uuid)
		return ""
	}

	var caUuid, err = core.Mutate(core.EndpointForModule("trust/ca/add"), map[string]any{"ca": map[string]string{
		"action": "internal", "descr": trust.CaDescr, "key_type": "prime256v1", "digest": "sha256", "lifetime": "30",
		"commonname": "a8-vpn-test-ca", "country": "NL",
	}})
	if err != nil {
		t.Fatalf("trust/ca/add: %v", err)
	}
	remove("ca", caUuid)
	trust.CaRef = refid("ca", caUuid)

	certUuid, err := core.Mutate(core.EndpointForModule("trust/cert/add"), map[string]any{"cert": map[string]string{
		"action": "internal", "descr": trust.CertDescr, "caref": trust.CaRef, "cert_type": "server_cert", "key_type": "prime256v1",
		"digest": "sha256", "lifetime": "30", "commonname": "a8-vpn-test-server", "country": "NL", "private_key_location": "firewall",
	}})
	if err != nil {
		t.Fatalf("trust/cert/add: %v", err)
	}
	remove("cert", certUuid)
	trust.CertRef = refid("cert", certUuid)
	return trust
}

// instanceTestOption returns the option with key of a form field
func instanceTestOption(form openvpn.Form, field string, key string) (openvpn.Option, bool) {
	for _, option := range form[field].Options {
		if option.Key == key {
			return option, true
		}
	}
	return openvpn.Option{}, false
}

func TestInstanceLifecycle(t *testing.T) {
	var vpn = instanceTestApi(t)
	var trust = instanceTestCertificates(t, "instance-lifecycle")
	var keyUuid, keyDescription = instanceTestStaticKey(t, vpn, "instance-lifecycle key", "crypt")

	// the get form lists the trust store, the static keys and the option lists (verb is a JSON list)
	var defaults, err = vpn.InstanceForm("")
	if err != nil {
		t.Fatalf("InstanceForm: %v", err)
	}
	if option, found := instanceTestOption(defaults, "ca", trust.CaRef); !found || option.Description != trust.CaDescr {
		t.Errorf("ca options lack %s %q: %+v", trust.CaRef, trust.CaDescr, defaults["ca"].Options)
	}
	if option, found := instanceTestOption(defaults, "cert", trust.CertRef); !found || option.Description != trust.CertDescr {
		t.Errorf("cert options lack %s: %+v", trust.CertRef, defaults["cert"].Options)
	}
	if option, found := instanceTestOption(defaults, "tls_key", keyUuid); !found || !strings.HasPrefix(option.Description, keyDescription+" [crypt") {
		t.Errorf("tls_key options lack %s: %+v", keyUuid, defaults["tls_key"].Options)
	}
	if len(defaults["verb"].Options) != 12 || defaults.Value("verb") != "3" || defaults.Value("role") != "server" ||
		defaults.Value("enabled") != "1" || defaults.Value("vpnid") != "" {
		t.Errorf("defaults: verb %+v role %q enabled %q vpnid %q", defaults["verb"], defaults.Value("role"), defaults.Value("enabled"), defaults.Value("vpnid"))
	}

	var description = testDescription("instance-lifecycle")
	var uuid = instanceTestCreate(t, vpn, openvpn.InstanceFields{
		"description": description, "role": "server", "server": "10.213.240.0/24", "proto": "udp4", "port": "11940",
		"ca": trust.CaRef, "cert": trust.CertRef, "tls_key": keyUuid, "data-ciphers": "AES-256-GCM,CHACHA20-POLY1305",
		"push_route": "10.213.0.0/16,192.168.213.0/24", "verb": "4", "keepalive_interval": "10", "keepalive_timeout": "60",
	})

	instance, err := vpn.InstanceGet(uuid)
	if err != nil {
		t.Fatalf("InstanceGet: %v", err)
	}
	if instance.Enabled != "0" || instance.Vpnid == "" || instance.Description != description || instance.Server != "10.213.240.0/24" ||
		instance.Proto != "udp4" || instance.Ca != trust.CaRef || instance.Cert != trust.CertRef || instance.TlsKey != keyUuid ||
		instance.DataCiphers != "AES-256-GCM,CHACHA20-POLY1305" || instance.PushRoute != "10.213.0.0/16,192.168.213.0/24" ||
		instance.Verb != "4" || instance.DevType != "tun" || instance.VerifyClientCert != "require" {
		t.Errorf("created instance: %+v", instance)
	}
	if found, err := vpn.InstanceGetByDescription(strings.ToUpper(description)); err != nil || found.Uuid != uuid {
		t.Errorf("InstanceGetByDescription: %+v %v", found, err)
	}
	form, err := vpn.InstanceForm(uuid)
	if err != nil || form.Value("cert") != trust.CertRef || form.Value("tls_key") != keyUuid || form.Value("verb") != "4" ||
		form.Value("data-ciphers") != "AES-256-GCM,CHACHA20-POLY1305" || form.Value("vpnid") != instance.Vpnid {
		t.Errorf("InstanceForm(uuid): %v %v", form.Values(), err)
	}
	if users, err := vpn.InstancesUsingStaticKey(keyUuid); err != nil || len(users) != 1 || users[0].Uuid != uuid {
		t.Errorf("InstancesUsingStaticKey: %+v %v", users, err)
	}

	// partial update: the other fields are kept
	var renamed = testDescription("instance-lifecycle renamed")
	if err := vpn.InstanceUpdate(uuid, openvpn.InstanceFields{"port": "11941", "description": renamed, "push_route": ""}); err != nil {
		t.Fatalf("InstanceUpdate: %v", err)
	}
	updated, err := vpn.InstanceGet(uuid)
	if err != nil || updated.Port != "11941" || updated.Description != renamed || updated.PushRoute != "" ||
		updated.Server != instance.Server || updated.TlsKey != keyUuid || updated.Vpnid != instance.Vpnid || updated.Enabled != "0" {
		t.Errorf("updated instance: %+v %v", updated, err)
	}

	// an empty vpnid would renumber the instance, it is refused without a request
	if err := vpn.InstanceUpdate(uuid, openvpn.InstanceFields{"vpnid": ""}); err == nil {
		t.Errorf("an empty vpnid must be refused")
	}

	// OPNsense validation
	var validation *api.ValidationError
	err = vpn.InstanceUpdate(uuid, openvpn.InstanceFields{"server": "10.213.240.0/30"})
	if !errors.As(err, &validation) || !strings.Contains(validation.Validations["instance.server"], "/29") {
		t.Errorf("want a /29 validation error, got %v", err)
	}
	err = vpn.InstanceUpdate(uuid, openvpn.InstanceFields{"keepalive_timeout": "15"})
	if !errors.As(err, &validation) || validation.Validations["instance.keepalive_timeout"] == "" {
		t.Errorf("want a keepalive validation error, got %v", err)
	}

	// disabling a disabled instance changes nothing (instances are never enabled here)
	if changed, err := vpn.InstanceSetEnabled(uuid, false); err != nil || changed {
		t.Errorf("InstanceSetEnabled(false): %v %v", changed, err)
	}

	if err := vpn.InstanceRemove(uuid); err != nil {
		t.Fatalf("InstanceRemove: %v", err)
	}
	if _, err := vpn.InstanceGet(uuid); !api.IsNotFound(err) {
		t.Errorf("the removed instance still exists: %v", err)
	}
	if err := vpn.InstanceRemove(uuid); !api.IsNotFound(err) {
		t.Errorf("removing again: want NotFoundError, got %v", err)
	}
}

func TestInstanceClient(t *testing.T) {
	var vpn = instanceTestApi(t)
	var trust = instanceTestCertificates(t, "instance-client")
	var description = testDescription("instance-client")

	// a client needs a remote
	var _, err = vpn.InstanceCreate(openvpn.InstanceFields{"description": description, "enabled": "0", "role": "client", "ca": trust.CaRef})
	var validation *api.ValidationError
	if !errors.As(err, &validation) || validation.Validations["instance.remote"] == "" {
		t.Fatalf("want a remote validation error, got %v", err)
	}

	var uuid = instanceTestCreate(t, vpn, openvpn.InstanceFields{
		"description": description, "role": "client", "ca": trust.CaRef, "remote": "vpn.example.com:1194,192.0.2.1",
		"username": "a8user", "password": "a8-secret", "proto": "tcp",
	})
	instance, err := vpn.InstanceGet(uuid)
	if err != nil || instance.Role != "client" || instance.Remote != "vpn.example.com:1194,192.0.2.1" || instance.Username != "a8user" {
		t.Fatalf("client: %+v %v", instance, err)
	}
	// quirk: search returns the password in clear text, the CLI masks it
	if instance.Password != "a8-secret" {
		t.Errorf("want the clear text password from search, got %q", instance.Password)
	}
	// username without password
	err = vpn.InstanceUpdate(uuid, openvpn.InstanceFields{"password": ""})
	if !errors.As(err, &validation) || validation.Validations["instance.username"] == "" {
		t.Errorf("want a username/password validation error, got %v", err)
	}
}

func TestInstanceUnknownUuid(t *testing.T) {
	var vpn = instanceTestApi(t)
	var core = coreApi(t)
	var ghost = instanceTestUuid()

	if err := vpn.InstanceUpdate(ghost, openvpn.InstanceFields{"description": testDescription("ghost")}); !api.IsNotFound(err) {
		t.Errorf("InstanceUpdate: want NotFoundError, got %v", err)
	}
	if _, err := vpn.InstanceSetEnabled(ghost, false); !api.IsNotFound(err) {
		t.Errorf("InstanceSetEnabled: want NotFoundError, got %v", err)
	}
	if err := vpn.InstanceRemove(ghost); !api.IsNotFound(err) {
		t.Errorf("InstanceRemove: want NotFoundError, got %v", err)
	}
	if _, err := vpn.InstanceForm(ghost); !api.IsNotFound(err) {
		t.Errorf("InstanceForm: want NotFoundError, got %v", err)
	}

	// quirk check (why InstanceUpdate checks the existence first): set/<well-formed unknown uuid> creates the
	// instance, a malformed uuid is answered with a bare "failed"
	instanceTestCleanup(t, vpn, ghost)
	var _, err = core.Mutate(core.EndpointForModule("openvpn/instances/set/"+ghost), map[string]any{"instance": map[string]string{
		"description": testDescription("ghost"), "enabled": "0", "vpnid": "", "role": "server", "server": "10.213.243.0/24",
		"verify_client_cert": "none", "authmode": "Local Database",
	}})
	if err != nil {
		t.Errorf("raw set on an unknown uuid: %v", err)
	}
	if _, err := vpn.InstanceGet(ghost); err != nil {
		t.Errorf("quirk changed? set did not create the unknown uuid %s: %v", ghost, err)
	}
	_, err = core.Mutate(core.EndpointForModule("openvpn/instances/set/not-a-uuid"), map[string]any{"instance": map[string]string{"enabled": "0"}})
	var validation *api.ValidationError
	if !errors.As(err, &validation) || len(validation.Validations) != 0 {
		t.Errorf("raw set on a malformed uuid: want a bare failed, got %v", err)
	}
}

func TestInstanceCreateVpnid(t *testing.T) {
	var vpn = instanceTestApi(t)
	var core = coreApi(t)
	var fields = map[string]string{
		"description": testDescription("instance-vpnid"), "enabled": "0", "role": "server", "server": "10.213.244.0/24",
		"verify_client_cert": "none", "authmode": "Local Database",
	}

	// quirk: add without vpnid fails, OPNsense only assigns one for an explicitly empty vpnid
	var uuid, err = core.Mutate(core.EndpointForModule("openvpn/instances/add"), map[string]any{"instance": fields})
	var validation *api.ValidationError
	if !errors.As(err, &validation) || validation.Validations["instance.vpnid"] == "" {
		if uuid != "" {
			instanceTestCleanup(t, vpn, uuid)
		}
		t.Errorf("add without vpnid: want a vpnid validation error, got %v", err)
	}

	// the library sends an empty vpnid
	var created = instanceTestCreate(t, vpn, openvpn.InstanceFields(fields))
	instance, err := vpn.InstanceGet(created)
	if err != nil || instance.Vpnid == "" || instance.Authmode != "Local Database" || instance.VerifyClientCert != "none" {
		t.Errorf("created: %+v %v", instance, err)
	}
	// an explicit vpnid is kept
	var used = map[string]bool{}
	var all, _ = vpn.InstanceList("")
	for _, other := range all {
		used[other.Vpnid] = true
	}
	var free = 900
	for used[fmt.Sprint(free)] {
		free++
	}
	if err := vpn.InstanceUpdate(created, openvpn.InstanceFields{"vpnid": fmt.Sprint(free)}); err != nil {
		t.Fatalf("set vpnid: %v", err)
	}
	if instance, _ := vpn.InstanceGet(created); instance.Vpnid != fmt.Sprint(free) {
		t.Errorf("vpnid %q, want %d", instance.Vpnid, free)
	}
}

// instanceTestRequireNoneEnabled skips unless no instance at all is enabled, so reconfigure can't start anything
func instanceTestRequireNoneEnabled(t *testing.T, vpn *openvpn.OpenVPNApi) {
	t.Helper()
	var instances, err = vpn.InstanceList("")
	if err != nil {
		t.Fatalf("InstanceList: %v", err)
	}
	for _, instance := range instances {
		if instance.Enabled != "0" {
			t.Skipf("instance %s (%q) is enabled, reconfigure could start it on the shared box", instance.Uuid, instance.Description)
		}
	}
}

func TestInstancesReconfigure(t *testing.T) {
	var vpn = instanceTestApi(t)
	instanceTestRequireNoneEnabled(t, vpn)
	if err := vpn.InstancesReconfigure(); err != nil {
		t.Errorf("InstancesReconfigure: %v", err)
	}
}
