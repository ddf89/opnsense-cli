// Live tests of the OpenVPN instance library. Every instance is created with enabled=0 and nothing is started:
// only apply (reconfigure) runs, and only while no instance at all is enabled

func instanceTestApi(t *testing.T) *openvpn.OpenVPNApi {
	t.Helper()
	return &openvpn.OpenVPNApi{OPNsense: coreApi(t)}
}

// instanceTestUuid returns a random, well-formed uuid that does not exist
func instanceTestUuid() string {
	var b = make([]byte, 16)
	_, _ = rand.Read(b)
	b[6] = b[6]&0x0f | 0x40 // version 4
	b[8] = b[8]&0x3f | 0x80 // RFC 4122 variant
	return fmt.Sprintf("%x-%x-%x-%x-%x", b[0:4], b[4:6], b[6:8], b[8:10], b[10:16])
}

// instanceTestCreate creates an instance, always disabled, and removes it (verified) when the test ends
func instanceTestCreate(t *testing.T, vpn *openvpn.OpenVPNApi, fields openvpn.InstanceFields) string {
	t.Helper()
	fields["enabled"] = "0" // never run anything on the shared box
	if !ownedByRun(fields["description"]) {
		t.Fatalf("instance description %q lacks the run prefix", fields["description"])
	}
	var uuid, err = vpn.InstanceCreate(fields)
	if err != nil {
		t.Fatalf("InstanceCreate: %v", err)
	}
	instanceTestCleanup(t, vpn, uuid)
	return uuid
}

// instanceTestCleanup removes the instance when the test ends (if it still exists) and verifies it is gone
func instanceTestCleanup(t *testing.T, vpn *openvpn.OpenVPNApi, uuid string) {
	t.Helper()
	t.Cleanup(func() {
		if err := vpn.InstanceRemove(uuid); err != nil && !api.IsNotFound(err) {
			t.Errorf("cleanup: removing instance %s: %v", uuid, err)
		}
		if _, err := vpn.InstanceGet(uuid); !api.IsNotFound(err) {
			t.Errorf("cleanup: instance %s still exists (%v)", uuid, err)
		}
	})
}

// instanceTestStaticKey creates a static key (generated by OPNsense) and removes it when the test ends
func instanceTestStaticKey(t *testing.T, vpn *openvpn.OpenVPNApi, label string, mode string) (string, string) {
	t.Helper()
	var keyType, err = openvpn.KeyTypeForMode(mode)
	if err != nil {
		t.Fatal(err)
	}
	material, err := vpn.GenerateKey(keyType)
	if err != nil {
		t.Fatalf("GenerateKey: %v", err)
	}
	var description = testDescription(label)
	uuid, err := vpn.StaticKeyCreate(openvpn.StaticKey{Description: description, Mode: mode, Key: material})
	if err != nil {
		t.Fatalf("StaticKeyCreate: %v", err)
	}
	staticKeyTestCleanup(t, vpn, uuid)
	return uuid, description
}

