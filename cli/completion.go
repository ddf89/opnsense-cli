package cli

import (
	"errors"
	"fmt"
	"io"
	"os"
	"strings"
	"time"

	coreapi "opnsense-cli/opnsense/api"
)

// Shell completion of one-shot command lines: "opn completion bash" prints a bash script that, on TAB, runs the
// hidden "opn __complete <line> <current word>" and offers what it prints. The candidates come from the same
// engine as TAB in the interactive shell (Session.Complete), including values loaded from the API (item names,
// interfaces, ...), which need the usual connection settings (OPN_URL, ... or .env) and give up after
// OPN_COMPLETE_TIMEOUT (default 3s) so an unreachable firewall never blocks the shell

// completeCommand is the hidden first argument the completion scripts call opn with
const completeCommand = "__complete"

// completeDefaultTimeout bounds a completion that loads values from the API
const completeDefaultTimeout = 3 * time.Second

// completeOptions are the options of opn completed before the first menu word
var completeOptions = []string{"-v", "--verbose", "-h", "--help", "--version"}

func init() {
	Root.Add(&Command{
		Name: "completion",
		Help: "print the completion script for bash",
		Long: `Prints a bash completion script for one-shot commands: TAB completes menu paths, commands, argument names
and values (item names and other values are loaded from the firewall, like TAB in the interactive shell).
Load it in the current shell or install it for every new one:

  source <(opn completion bash)
  opn completion bash > ~/.local/share/bash-completion/completions/opn

name= registers the script for other program names too (e.g. a renamed release binary). Values loaded from
the firewall use the connection settings of opn (OPN_URL, ... or .env in the current directory) and are given
up after OPN_COMPLETE_TIMEOUT (default 3s); menus, commands and argument names always complete.`,
		Args: []Arg{
			{Name: "shell", Positional: true, Default: "bash", Values: []string{"bash"}, Help: "the shell (bash)"},
			{Name: "name", Type: List, Default: "opn", Validate: completionValidateNames,
				Help: "the program names to complete (comma separated)"},
		},
		Run: func(c *Context, args *Args) error {
			_, err := io.WriteString(c.Out, completionBashScript(args.List("name")))
			return err
		},
	})
}

// completionValidateNames accepts program names usable in the generated script
func completionValidateNames(value string) error {
	for _, name := range strings.Split(value, ",") {
		if name == "" || strings.ContainsAny(name, " \t\n'\"$`\\;&|<>(){}*?[]!#") {
			return fmt.Errorf("%q is not a usable program name", name)
		}
	}
	return nil
}

// completionBashScript is the bash completion script for the program names
func completionBashScript(names []string) string {
	return `# bash completion for opn, generated by "opn completion bash"
#
#   source <(opn completion bash)

_opn_completion() {
    local cur="${COMP_WORDS[COMP_CWORD]}"
    local program="${COMP_WORDS[0]}"
    [[ $program == "~/"* ]] && program="$HOME/${program#\~/}"
    local IFS=$'\n'
    # opn prints the candidates for the line up to the cursor, cut to the part bash replaces (bash splits
    # words at = and :, so after "sort=i" only "i" is replaced)
    COMPREPLY=($("$program" ` + completeCommand + ` "${COMP_LINE:0:COMP_POINT}" "$cur" 2>/dev/null))
    # argument names (name=) and menu paths (/a/b/) continue without a space
    if [[ ${#COMPREPLY[@]} -eq 1 && ${COMPREPLY[0]} == *[=/] ]]; then
        compopt -o nospace 2>/dev/null
    fi
}
complete -o default -F _opn_completion ` + strings.Join(names, " ") + "\n"
}

// runComplete answers "opn __complete <line> [<current word>]": line is the command line up to the cursor
// (program name included), current the word the shell replaces (empty after a space). It prints one candidate
// per line and always succeeds, completions must not print errors
func runComplete(session *Session, args []string, stdout io.Writer) int {
	if len(args) == 0 {
		return 0
	}
	var current = ""
	if len(args) > 1 {
		current = args[1]
	}
	var timeout = completeDefaultTimeout
	if value, err := time.ParseDuration(os.Getenv("OPN_COMPLETE_TIMEOUT")); err == nil && value > 0 {
		timeout = value
	}

	// values loaded from the API can take long (unreachable firewall): give up after the timeout and offer what
	// completes without the API (menus, commands, argument names, fixed values), the process exits right after
	var offline = NewSession(io.Discard, io.Discard)
	offline.Configure = func() (*coreapi.OPNsense, error) { return nil, errors.New("no API while completing offline") }
	var candidates = completeLine(offline, args[0], current)
	var done = make(chan []string, 1)
	go func() { done <- completeLine(session, args[0], current) }()
	select {
	case candidates = <-done:
	case <-time.After(timeout):
	}
	for _, candidate := range candidates {
		_, _ = fmt.Fprintln(stdout, candidate)
	}
	return 0
}

// completeLine returns the candidates for a one-shot command line being typed (with the program name), cut to
// the part of the partial word the shell replaces: current is how the shell sees that word
func completeLine(session *Session, line string, current string) []string {
	// drop the program name and the options before the first menu word
	line = strings.TrimLeft(line, " \t")
	var end = strings.IndexAny(line, " \t")
	if end < 0 {
		return nil // still typing the program name
	}
	line = line[end:]
	for {
		var trimmed = strings.TrimLeft(line, " \t")
		var word, rest, complete = strings.Cut(trimmed, " ")
		if !strings.HasPrefix(word, "-") || word == "-" {
			break
		}
		if !complete {
			// completing an option
			var candidates []string
			for _, option := range completeOptions {
				if strings.HasPrefix(option, word) {
					candidates = append(candidates, option)
				}
			}
			return completeTrim(candidates, word, current)
		}
		line = rest
	}

	var candidates, start = session.Complete(strings.TrimLeft(line, " \t"))
	var trimmedLine = strings.TrimLeft(line, " \t")
	return completeTrim(candidates, trimmedLine[start:], current)
}

// completeTrim cuts the candidates (replacements of partial) to what replaces current, the end of partial the
// shell considers the word being completed
func completeTrim(candidates []string, partial string, current string) []string {
	if !strings.HasSuffix(partial, current) {
		return candidates
	}
	var cut = partial[:len(partial)-len(current)]
	var trimmed = make([]string, 0, len(candidates))
	for _, candidate := range candidates {
		if strings.HasPrefix(candidate, cut) {
			trimmed = append(trimmed, candidate[len(cut):])
		}
	}
	return trimmed
}
