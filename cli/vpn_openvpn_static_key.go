// /vpn/openvpn/static-key: the static keys of VPN > OpenVPN > Instances > Static Keys, used by instances for
// tls-auth / tls-crypt (instance tls-key=). Items are selected by the # of print, the uuid or the description.
// The key material is only shown by show and print json, never in the print table or print detail

const (
	openvpnStaticKeyItemHelp = "the #, uuid or description of the static key"
	openvpnStaticKeyHint     = `Instances using the key get the change with "/vpn/openvpn/instance apply".`
)

func openvpnStaticKeyFieldArgs(add bool) []Arg {
	var args = []Arg{
		{Name: "description", Required: add, Help: "description, also the name of the key", Validate: openvpnStaticKeyValidateDescription},
		{Name: "mode", Values: openvpn.StaticKeyModes, Validate: openvpnInstanceNotEmpty,
			Help: "auth (tls-auth), crypt (tls-crypt, the default) or crypt-v2 (tls-crypt-v2 server key)"},
		{Name: "key", Help: "the key file content, generated by OPNsense when neither key nor key-file is given", Validate: openvpnStaticKeyValidateKey},
		{Name: "key-file", Help: "read the key from this local file (e.g. ta.key)"},
	}
	if !add {
		args = append(args, Arg{Name: "regenerate", Type: Bool, Help: "let OPNsense generate a new key for the (new) mode"})
	}
	return args
}

func init() {
	var menu = Root.Menu("vpn/openvpn/static-key")
	menu.Help = "static keys for tls-auth / tls-crypt (VPN > OpenVPN > Instances > Static Keys)"
	var item = Arg{Name: "item", Help: openvpnStaticKeyItemHelp, Positional: true, Required: true, Complete: openvpnStaticKeyNames}
	menu.Add(
		&Command{Name: "print", Help: "list the static keys (without the key material)", Args: []Arg{
			{Name: "detail", Type: Bool, Help: "show all fields of every key, except the key itself"},
			{Name: "json", Type: Bool, Help: "one JSON object per line, as the API returns them (including the key)"},
			{Name: "search", Help: "only keys where the description contains this text"},
		}, Run: openvpnStaticKeyPrint},
		&Command{Name: "show", Help: "show one static key, including the key material", Args: []Arg{item}, Run: openvpnStaticKeyShow},
		&Command{Name: "add", Help: "add a static key, prints its uuid",
			Long: `Without key= or key-file= OPNsense generates a new key for the mode (default crypt). The description
names the key: if it exists already, add fails unless replace is given, then that key is replaced completely (a
new key is generated unless one is given).`,
			Args:  append(openvpnStaticKeyFieldArgs(true), Arg{Name: "replace", Type: Bool, Help: "replace the key with the same description"}),
			Check: openvpnStaticKeyCheck,
			Run:   openvpnStaticKeyAdd},
		&Command{Name: "set", Help: "change fields of a static key, the others are kept",
			Long:  "description= renames the key, regenerate replaces the key by a new one.\n" + openvpnStaticKeyHint,
			Args:  append([]Arg{item}, openvpnStaticKeyFieldArgs(false)...),
			Check: openvpnStaticKeyCheck,
			Run:   openvpnStaticKeySet},
		&Command{Name: "remove", Help: "remove a static key, refused while instances use it", Args: []Arg{item}, Run: openvpnStaticKeyRemove},
	)
}

// --- validation

func openvpnStaticKeyValidateDescription(value string) error {
	if strings.TrimSpace(value) == "" {
		return errors.New("must not be empty")
	}
	return openvpnInstanceValidateText(value)
}

func openvpnStaticKeyValidateKey(value string) error {
	if strings.TrimSpace(value) == "" {
		return errors.New("must not be empty, leave it out to generate one")
	}
	return openvpnInstanceValidateKey(value)
}

func openvpnStaticKeyCheck(args *Args) error {
	var sources []string
	for _, name := range []string{"key", "key-file", "regenerate"} {
		if spec := exactArg(args.command, name); spec != nil && args.Has(name) && (spec.Type != Bool || args.Bool(name)) {
			sources = append(sources, name)
		}
	}
	if len(sources) > 1 {
		return fmt.Errorf("give only one of %s", strings.Join(sources, ", "))
	}
	return nil
}

// --- lookups

// openvpnStaticKeySearch returns the matching keys in API order with the raw rows for json
func openvpnStaticKeySearch(api *openvpn.OpenVPNApi, searchPhrase string) ([]openvpn.StaticKey, []json.RawMessage, error) {
	var endpoint = api.EndpointForPluginControllerMethod("openvpn", "instances", "search_static_key")
	var rows, err = coreapi.Search[json.RawMessage](api.OPNsense, endpoint, searchPhrase)
	if err != nil {
		return nil, nil, err
	}
	var keys = make([]openvpn.StaticKey, len(rows))
	for i, row := range rows {
		if err := json.Unmarshal(row, &keys[i]); err != nil {
			return nil, nil, fmt.Errorf("unexpected openvpn static key from OPNsense: %w", err)
		}
	}
	return keys, rows, nil
}

func openvpnStaticKeyUuid(key openvpn.StaticKey) string {
	return key.Uuid
}

func openvpnStaticKeyDescriptions(key openvpn.StaticKey) []string {
	return []string{key.Description}
}

func openvpnStaticKeySelect(c *Context, api *openvpn.OpenVPNApi, selector string) (openvpn.StaticKey, []openvpn.StaticKey, error) {
	var keys, _, err = openvpnStaticKeySearch(api, "")
	if err != nil {
		return openvpn.StaticKey{}, nil, err
	}
	var key, selectErr = Select(c, selector, keys, openvpnStaticKeyUuid, openvpnStaticKeyDescriptions)
	return key, keys, selectErr
}

// openvpnStaticKeyNames completes static keys by description (also used by instance tls-key=)
func openvpnStaticKeyNames(c *Context) []string {
	var api, err = openvpnApi(c)
	if err != nil {
		return nil
	}
	var keys, listErr = api.StaticKeyList("")
	if listErr != nil {
		return nil
	}
	var names []string
	for _, key := range keys {
		names = append(names, key.Description)
	}
	return names
}

// openvpnStaticKeyResolve maps instance tls-key= (uuid or description, "" for none) to the static key uuid
func openvpnStaticKeyResolve(_ *Context, api *openvpn.OpenVPNApi, value string) (string, error) {
	value = strings.TrimSpace(value)
	if value == "" {
		return "", nil
	}
	var keys, err = api.StaticKeyList("")
	if err != nil {
		return "", err
	}
	for _, key := range keys {
		if strings.EqualFold(key.Uuid, value) {
			return key.Uuid, nil
		}
	}
	var matches = coreapi.Filter(keys, func(key openvpn.StaticKey) bool { return strings.EqualFold(key.Description, value) })
	switch len(matches) {
	case 1:
		return matches[0].Uuid, nil
	case 0:
		return "", &coreapi.NotFoundError{Name: fmt.Sprintf("tls-key %q, see /vpn/openvpn/static-key print", value)}
	default:
		var uuids = make([]string, len(matches))
		for i, match := range matches {
			uuids[i] = match.Uuid
		}
		return "", &coreapi.TooManyFoundError{Name: fmt.Sprintf("tls-key %q matches %s, give the uuid instead", value, strings.Join(uuids, ", "))}
	}
}

// openvpnStaticKeyMaterial returns the key from key= or key-file=, or a new one generated for mode
func openvpnStaticKeyMaterial(api *openvpn.OpenVPNApi, args *Args, mode string) (string, error) {
	if args.Has("key") {
		return strings.TrimSpace(args.String("key")), nil
	}
	if args.Has("key-file") {
		var content, err = os.ReadFile(args.String("key-file"))
		if err != nil {
			return "", fmt.Errorf("key-file: %w", err)
		}
		var key = strings.TrimSpace(string(content))
		if key == "" {
			return "", fmt.Errorf("key-file: %s is empty", args.String("key-file"))
		}
		if err := openvpnInstanceValidateKey(key); err != nil {
			return "", fmt.Errorf("key-file: the key %w", err)
		}
		return key, nil
	}
	var keyType, err = openvpn.KeyTypeForMode(mode)
	if err != nil {
		return "", err
	}
	return api.GenerateKey(keyType)
}

// --- output

// openvpnStaticKeyUsers returns the descriptions (or uuids) of the instances using a key
func openvpnStaticKeyUsers(instances []openvpn.Instance, uuid string) []string {
	var users []string
	for _, instance := range instances {
		if strings.EqualFold(instance.TlsKey, uuid) {
			var name = instance.Description
			if name == "" {
				name = instance.Uuid
			}
			users = append(users, name)
		}
	}
	return users
}

func openvpnStaticKeyModeText(key openvpn.StaticKey) string {
	return key.Mode
}

func openvpnStaticKeyDetail(key openvpn.StaticKey, instances []openvpn.Instance) [][2]string {
	return [][2]string{
		{"uuid", key.Uuid},
		{"description", key.Description},
		{"mode", openvpnStaticKeyModeText(key)},
		{"used-by", strings.Join(openvpnStaticKeyUsers(instances, key.Uuid), ", ")},
	}
}

func openvpnStaticKeyPrint(c *Context, args *Args) error {
	var api, err = openvpnApi(c)
	if err != nil {
		return err
	}
	var keys, raw, searchErr = openvpnStaticKeySearch(api, args.String("search"))
	if searchErr != nil {
		return searchErr
	}
	if args.Bool("json") {
		for _, row := range raw {
			c.Println(string(row))
		}
		return nil
	}

	var instances, listErr = api.InstanceList("")
	if listErr != nil {
		return listErr
	}
	var uuids = make([]string, len(keys))
	for i, key := range keys {
		uuids[i] = key.Uuid
	}
	if args.Bool("detail") {
		var items = make([][][2]string, len(keys))
		for i, key := range keys {
			items[i] = openvpnStaticKeyDetail(key, instances)
		}
		c.Details(items, uuids)
		return nil
	}
	var rows = make([][]string, len(keys))
	for i, key := range keys {
		rows[i] = []string{key.Description, openvpnStaticKeyModeText(key), strings.Join(openvpnStaticKeyUsers(instances, key.Uuid), ", ")}
	}
	c.Items([]string{"DESCRIPTION", "MODE", "USED-BY"}, rows, uuids)
	return nil
}

func openvpnStaticKeyShow(c *Context, args *Args) error {
	var api, err = openvpnApi(c)
	if err != nil {
		return err
	}
	var key, _, selectErr = openvpnStaticKeySelect(c, api, args.String("item"))
	if selectErr != nil {
		return selectErr
	}
	var instances, listErr = api.InstanceList("")
	if listErr != nil {
		return listErr
	}
	c.Fields(openvpnStaticKeyDetail(key, instances))
	// the key file has several lines, so it follows indented
	c.Println("key:")
	for _, line := range strings.Split(strings.TrimSpace(key.Key), "\n") {
		c.Println("  " + strings.TrimRight(line, "\r"))
	}
	return nil
}

// --- changes

func openvpnStaticKeyAdd(c *Context, args *Args) error {
	var api, err = openvpnApi(c)
	if err != nil {
		return err
	}
	var description = strings.TrimSpace(args.String("description"))
	var mode = "crypt"
	if args.Has("mode") {
		mode = openvpnInstanceCanonical(openvpn.StaticKeyModes, args.String("mode"))
	}

	var keys, _, searchErr = openvpnStaticKeySearch(api, "")
	if searchErr != nil {
		return searchErr
	}
	var existing = coreapi.Filter(keys, func(key openvpn.StaticKey) bool { return strings.EqualFold(key.Description, description) })
	switch {
	case len(existing) > 1:
		var uuids = make([]string, len(existing))
		for i, key := range existing {
			uuids[i] = key.Uuid
		}
		return &coreapi.TooManyFoundError{Name: fmt.Sprintf("there are %d static keys with description %q (%s), change or remove them with set or remove",
			len(existing), description, strings.Join(uuids, ", "))}
	case len(existing) == 1 && !args.Bool("replace"):
		return fmt.Errorf("a static key with description %q exists already (%s), change it with set or replace it with add ... replace",
			existing[0].Description, existing[0].Uuid)
	}

	var material, materialErr = openvpnStaticKeyMaterial(api, args, mode)
	if materialErr != nil {
		return materialErr
	}
	if len(existing) == 0 {
		var uuid, createErr = api.StaticKeyCreate(openvpn.StaticKey{Description: description, Mode: mode, Key: material})
		if createErr != nil {
			return createErr
		}
		c.Println(uuid)
		return nil
	}
	var fields = openvpn.StaticKeyFields{"description": description, "mode": mode, "key": material}
	if err := api.StaticKeyUpdate(existing[0].Uuid, fields); err != nil {
		return err
	}
	c.Infof("replaced the existing static key %q", existing[0].Description)
	c.Println(existing[0].Uuid)
	return nil
}

func openvpnStaticKeySet(c *Context, args *Args) error {
	var fields = openvpn.StaticKeyFields{}
	if args.Has("description") {
		fields["description"] = strings.TrimSpace(args.String("description"))
	}
	if args.Has("mode") {
		fields["mode"] = openvpnInstanceCanonical(openvpn.StaticKeyModes, args.String("mode"))
	}
	var newKey = args.Has("key") || args.Has("key-file") || args.Bool("regenerate")
	if len(fields) == 0 && !newKey {
		return errors.New("set: nothing to change, give at least one of description=, mode=, key=, key-file= or regenerate (type \"set ?\" for help)")
	}

	var api, err = openvpnApi(c)
	if err != nil {
		return err
	}
	var key, keys, selectErr = openvpnStaticKeySelect(c, api, args.String("item"))
	if selectErr != nil {
		return selectErr
	}
	if description, renamed := fields["description"]; renamed {
		for _, other := range keys {
			if other.Uuid != key.Uuid && strings.EqualFold(other.Description, description) {
				return fmt.Errorf("another static key with description %q exists already (%s)", description, other.Uuid)
			}
		}
	}
	var mode = key.Mode
	if newMode, changed := fields["mode"]; changed {
		mode = newMode
	}
	if newKey {
		var material, materialErr = openvpnStaticKeyMaterial(api, args, mode)
		if materialErr != nil {
			return materialErr
		}
		fields["key"] = material
	} else if mode != key.Mode {
		c.Infof("the key was made for mode %s, give regenerate to generate one for %s", key.Mode, mode)
	}
	return api.StaticKeyUpdate(key.Uuid, fields)
}

func openvpnStaticKeyRemove(c *Context, args *Args) error {
	var api, err = openvpnApi(c)
	if err != nil {
		return err
	}
	var key, _, selectErr = openvpnStaticKeySelect(c, api, args.String("item"))
	if selectErr != nil {
		return selectErr
	}
	// OPNsense deletes keys in use, leaving the instances with a dangling reference
	var instances, listErr = api.InstancesUsingStaticKey(key.Uuid)
	if listErr != nil {
		return listErr
	}
	if users := openvpnStaticKeyUsers(instances, key.Uuid); len(users) > 0 {
		return fmt.Errorf("the static key %q is used by the instances %s, change their tls-key first", key.Description, strings.Join(users, ", "))
	}
	return api.StaticKeyRemove(key.Uuid)
}
